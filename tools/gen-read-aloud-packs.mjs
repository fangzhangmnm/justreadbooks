// tools/gen-read-aloud-packs.mjs —— 从兄弟仓 `../20260903 PWA Models`（GitHub fangzhangmnm/pwa-models）把朗读音色内嵌进 app：
//   voices/<id>.json（音色定义：由哪几个包组成、署名与条款原文）+ 它点名的每个包的 manifest.json（原样）
//   → src/read-aloud-packs.generated.ts。packId = sha256(manifest.json 字节) 就是 app 钉的信任根；音色定义里写的 packId 对不上就报错。
// 用法：node tools/gen-read-aloud-packs.mjs（模型仓加 / 改了朗读音色必须重跑；test/i18n-and-assets 守着不漂移）。生成物勿手改。
// 只内嵌模型仓里**已经有**的：没发布的音色不进 app（界面上不许出现下不到的下载钮）。
// 例外 = `tools/local-voices/`（2026-10-06）：许可证不许再分发的音色（小雅）只内嵌清单、列进 READ_ALOUD_IMPORT_ONLY，界面上没有下载钮、只有本机导入。
// created 2026-10-01 by Claude Fable 5.1（抄 WebXiaoHeiWu tools/gen-asr-packs.mjs）
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MODELS_ROOT = join(ROOT, "..", "20260903 PWA Models");
export const LOCAL_ROOT = join(ROOT, "tools", "local-voices");   // 同形的小目录：<id>.json + packs/<slug>/manifest.json（分片不进仓）
export const OUT = join(ROOT, "src", "read-aloud-packs.generated.ts");
/** 退役包：JRB 以前内嵌过、现在不内嵌的音色权重包（git 史可查）。设置 →「朗读」的「清理旧版音色」只删这张表里的包——家规「只动自己认得的」：
 *  这些 slug 是 JRB 自己下过的，别的 app 认不认得不归我们猜。表只增（包只增不删，退役的也一直认得）。added 2026-10-21 by Claude Opus 5.5（周账 F-29 第 5 步）。 */
export const RETIRED = [
  "voice-tsukuyomi-chan-6lang-fp16-20260613",        // 原版つくよみちゃん：v0.2.1–0.2.11 内嵌（a4606a8 换成中英增强）
  "voice-tsukuyomi-chan-zhen-6lang-fp16-20261002",   // 中英增强 20261002：v0.2.12–0.2.20（v0.2.21 换成 dur 包，逐样本相同）
];

/** 一个模型仓目录 → { voices, packs }（和库的 VoiceDef / EmbeddedPack 同形）。音色定义和清单对不上 → 抛错。 */
export function collect(modelsRoot) {
  const voices = {}, packs = {};
  const vdir = join(modelsRoot, "voices");
  for (const f of existsSync(vdir) ? readdirSync(vdir).filter((n) => n.endsWith(".json")).sort() : []) {
    const def = JSON.parse(readFileSync(join(vdir, f), "utf8"));
    const slugs = [...new Set([...def.packs, ...Object.values(def.langPacks).flat()])];
    for (const slug of slugs) {
      const p = join(modelsRoot, "packs", slug, "manifest.json");
      if (!existsSync(p)) throw new Error(`voice ${def.id}: pack ${slug} is not in the models repo`);
      const bytes = readFileSync(p);
      const packId = createHash("sha256").update(bytes).digest("hex");
      if (def.packIds?.[slug] !== packId) throw new Error(`voice ${def.id}: packId of ${slug} is ${packId}, the voice definition says ${def.packIds?.[slug]}`);
      packs[slug] = { packId, manifest: JSON.parse(bytes.toString("utf8")) };
    }
    voices[def.id] = def;
  }
  return { voices, packs };
}

export function render() {
  if (!existsSync(MODELS_ROOT)) return null;
  const { voices, packs } = collect(MODELS_ROOT);
  const local = collect(LOCAL_ROOT);
  for (const id of Object.keys(local.voices)) if (voices[id]) throw new Error(`local voice ${id} clashes with a published voice`);
  Object.assign(voices, local.voices); Object.assign(packs, local.packs);
  const importOnly = Object.keys(local.voices);
  const retired = {};
  for (const slug of RETIRED) {
    if (packs[slug]) throw new Error(`retired pack ${slug} is still embedded by a current voice — remove it from RETIRED or from the voice`);
    const p = join(MODELS_ROOT, "packs", slug, "manifest.json");
    if (!existsSync(p)) throw new Error(`retired pack ${slug} is not in the models repo (packs are never removed; check the slug)`);
    const bytes = readFileSync(p);
    retired[slug] = { packId: createHash("sha256").update(bytes).digest("hex"), manifest: JSON.parse(bytes.toString("utf8")) };
  }
  const lines = (o) => Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  return `// 生成物：node tools/gen-read-aloud-packs.mjs（源 = ../20260903 PWA Models 的 voices/*.json + 它们点名的 packs/*/manifest.json，+ tools/local-voices/ 的本机导入音色）。勿手改。
// packId = sha256(manifest.json 原字节) = app 钉死的信任根；分片字节从任何主机 / 文件来都先对 manifest.chunks[].sha256 再用。
// generated by tools/gen-read-aloud-packs.mjs (Claude Fable 5.1; RETIRED table added by Claude Opus 5.5)
import type { EmbeddedPack, VoiceDef } from "@internal/read-aloud";
import type { EmbeddedPack as PackStoreEmbeddedPack } from "@internal/model-packs";   // 同一份 manifest.json 两个库各声明自己读的字段；交叉类型让这张表能原样喂给两边（0.2.19）
export const READ_ALOUD_VOICES: Record<string, VoiceDef> = {
${lines(voices)}
};
export const READ_ALOUD_PACKS: Record<string, EmbeddedPack & PackStoreEmbeddedPack> = {
${lines(packs)}
};
/** 只准本机导入的音色（tools/local-voices/）：没有下载来源，界面上不给下载钮。 */
export const READ_ALOUD_IMPORT_ONLY: readonly string[] = ${JSON.stringify(importOnly)};
/** 退役包（JRB 以前内嵌过、现在不用）：只给「清理旧版音色」认领用——问缓存里还剩多少、删掉。永不下载。 */
export const READ_ALOUD_RETIRED_PACKS: Record<string, PackStoreEmbeddedPack> = {
${lines(retired)}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = render();
  if (!out) { console.error("[gen-read-aloud-packs] models repo not found at", MODELS_ROOT); process.exit(1); }
  writeFileSync(OUT, out);
  console.log("[gen-read-aloud-packs] →", OUT);
}
