// tools/gen-read-aloud-packs.mjs —— 从兄弟仓 `../20260903 PWA Models`（GitHub fangzhangmnm/pwa-models）把朗读语音包（task = "tts"）的
// manifest.json 原样内嵌成 src/read-aloud-packs.generated.ts：packId = sha256(manifest.json 字节) 就是 app 钉的信任根。
// 用法：node tools/gen-read-aloud-packs.mjs（模型仓加 / 改了朗读包必须重跑；test/i18n-and-assets 守着不漂移）。生成物勿手改。
// created 2026-10-01 by Claude Fable 5.1（抄 WebXiaoHeiWu tools/gen-asr-packs.mjs）
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MODELS_DIR = join(ROOT, "..", "20260903 PWA Models", "packs");
export const OUT = join(ROOT, "src", "read-aloud-packs.generated.ts");

export function render() {
  if (!existsSync(MODELS_DIR)) return null;
  const entries = [];
  for (const slug of readdirSync(MODELS_DIR).sort()) {
    const p = join(MODELS_DIR, slug, "manifest.json");
    if (!existsSync(p)) continue;
    const bytes = readFileSync(p);
    const manifest = JSON.parse(bytes.toString("utf8"));
    if (manifest.task !== "tts") continue;
    entries.push({ slug, packId: createHash("sha256").update(bytes).digest("hex"), manifest });
  }
  const body = entries.map((e) => `  ${JSON.stringify(e.slug)}: { packId: ${JSON.stringify(e.packId)}, manifest: ${JSON.stringify(e.manifest)} },`).join("\n");
  return `// 生成物：node tools/gen-read-aloud-packs.mjs（源 = ../20260903 PWA Models/packs/*/manifest.json 里 task = "tts" 的包）。勿手改。
// packId = sha256(manifest.json 原字节) = app 钉死的信任根；分片字节从任何主机 / 文件来都先对 manifest.chunks[].sha256 再用。
// generated by tools/gen-read-aloud-packs.mjs (Claude Fable 5.1)
import type { EmbeddedPack } from "@internal/read-aloud";
export const READ_ALOUD_PACKS: Record<string, EmbeddedPack> = {
${body}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = render();
  if (!out) { console.error("[gen-read-aloud-packs] models repo not found at", MODELS_DIR); process.exit(1); }
  writeFileSync(OUT, out);
  console.log("[gen-read-aloud-packs] →", OUT);
}
